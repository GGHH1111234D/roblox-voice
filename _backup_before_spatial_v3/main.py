"""
WebRTC 3D Spatial Audio Signaling & PIN Verification Server (FastAPI)
=====================================================================
نظام ربط صوتي مكاني خفيف ومباشر برمز PIN فقط (بدون ديسكورد نهائياً).

1. يستقبل إحداثيات اللاعبين ورموز الـ PIN من روبلوكس عبر `POST /update_locations`.
2. يربط متصفح الويب باللاعب في اللعبة تلقائياً عبر رمز الـ PIN المكون من 4 أرقام.
3. يبث الإحداثيات كل 0.5 ثانية عبر WebSocket لجميع المتصلين لتحديث الـ PannerNode ثلاثي الأبعاد.
"""

from __future__ import annotations

import asyncio
import logging
import os
import re
import uuid
from contextlib import asynccontextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, AsyncIterator

import uvicorn
from fastapi import FastAPI, Header, HTTPException, Query, WebSocket, WebSocketDisconnect
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)-7s | %(message)s",
)
logger = logging.getLogger("roblox-spatial-voice")

BASE_DIR = Path(__file__).resolve().parent
STATIC_DIR = BASE_DIR / "static"

LOCATION_BROADCAST_INTERVAL = 0.5
ROBLOX_API_SECRET = os.environ.get("ROBLOX_API_SECRET", "").strip()


# ------------------------------------------------------------------------------
# In-Memory Location & PIN Store
# ------------------------------------------------------------------------------
class PlayerPosition(BaseModel):
    pin: str = Field(default="", description="4-digit PIN generated by Roblox")
    username: str = Field(default="", description="Roblox player name")
    x: float
    y: float
    z: float
    yaw: float = Field(default=0.0)


# In-memory mapping: UserId -> { userId, pin, username, x, y, z, yaw }
player_locations: dict[str, dict[str, Any]] = {}
# Quick lookup: PIN (str) -> UserId (str)
pin_to_user: dict[str, str] = {}


# ------------------------------------------------------------------------------
# Global Room Signaling Manager
# ------------------------------------------------------------------------------
@dataclass
class PeerSession:
    peer_id: str
    pin: str
    roblox_user_id: str
    username: str
    websocket: WebSocket


class GlobalRoomManager:
    def __init__(self) -> None:
        self.peers: dict[str, PeerSession] = {}

    @staticmethod
    def _sanitize_pin(raw_pin: str) -> str:
        return re.sub(r"\D", "", (raw_pin or "").strip())[:6]

    @staticmethod
    def _sanitize_username(raw_name: str, fallback_id: str) -> str:
        cleaned = re.sub(r"[^\w\-. ]", "", (raw_name or "").strip())[:24].strip()
        return cleaned if cleaned else f"Player_{fallback_id[:4]}"

    async def connect(
        self, websocket: WebSocket, raw_pin: str, raw_username: str
    ) -> PeerSession:
        await websocket.accept()

        peer_id = uuid.uuid4().hex[:8]
        pin = self._sanitize_pin(raw_pin)

        # Look up if Roblox already reported this PIN
        matched_user_id = pin_to_user.get(pin, "")
        matched_data = player_locations.get(matched_user_id, {})
        roblox_username = matched_data.get("username", "")

        username = roblox_username or self._sanitize_username(
            raw_username, fallback_id=pin or peer_id
        )

        existing_peers = [
            {
                "peerId": pid,
                "pin": session.pin,
                "robloxUserId": session.roblox_user_id,
                "username": session.username,
            }
            for pid, session in self.peers.items()
        ]

        session = PeerSession(
            peer_id=peer_id,
            pin=pin,
            roblox_user_id=matched_user_id,
            username=username,
            websocket=websocket,
        )
        self.peers[peer_id] = session

        logger.info(
            "Peer connected: %s | PIN=%s | UserId=%s | Online=%d",
            username,
            pin or "none",
            matched_user_id or "unlinked",
            len(self.peers),
        )

        # 1. Send welcome message with room snapshot
        await self._safe_send(
            session,
            {
                "type": "welcome",
                "peerId": peer_id,
                "pin": pin,
                "robloxUserId": matched_user_id,
                "username": username,
                "peers": existing_peers,
            },
        )

        # 2. Push current locations immediately
        if player_locations:
            await self._safe_send(
                session,
                {
                    "type": "locations",
                    "locations": player_locations,
                    "pinMap": pin_to_user,
                },
            )

        # 3. Notify other peers
        await self.broadcast(
            {
                "type": "peer-joined",
                "peerId": peer_id,
                "pin": pin,
                "robloxUserId": matched_user_id,
                "username": username,
            },
            exclude_peer_id=peer_id,
        )

        return session

    async def disconnect(self, peer_id: str) -> None:
        removed = self.peers.pop(peer_id, None)
        if not removed:
            return

        logger.info(
            "Peer left: %s (PIN=%s, PeerId=%s) | Remaining=%d",
            removed.username,
            removed.pin or "none",
            peer_id,
            len(self.peers),
        )
        await self.broadcast({"type": "peer-left", "peerId": peer_id})

    async def relay_to_peer(
        self, sender: PeerSession, target_peer_id: str, payload: dict[str, Any]
    ) -> None:
        target = self.peers.get(target_peer_id)
        if not target:
            return

        outbound = {
            **payload,
            "sender": sender.peer_id,
            "pin": sender.pin,
            "robloxUserId": sender.roblox_user_id,
            "username": sender.username,
        }
        await self._safe_send(target, outbound)

    async def broadcast(
        self, payload: dict[str, Any], exclude_peer_id: str | None = None
    ) -> None:
        stale_ids: list[str] = []
        for pid, session in list(self.peers.items()):
            if pid == exclude_peer_id:
                continue
            if not await self._safe_send(session, payload):
                stale_ids.append(pid)

        for pid in stale_ids:
            self.peers.pop(pid, None)

    async def _safe_send(self, session: PeerSession, payload: dict[str, Any]) -> bool:
        try:
            await session.websocket.send_json(payload)
            return True
        except Exception:
            return False


room = GlobalRoomManager()


# ------------------------------------------------------------------------------
# Continuous Background Location Broadcast Loop
# ------------------------------------------------------------------------------
async def broadcast_locations_loop() -> None:
    while True:
        await asyncio.sleep(LOCATION_BROADCAST_INTERVAL)
        if room.peers and player_locations:
            # Refresh peer linkings if a player connected web before Roblox reported their PIN
            for session in room.peers.values():
                if session.pin and not session.roblox_user_id:
                    matched_id = pin_to_user.get(session.pin)
                    if matched_id:
                        session.roblox_user_id = matched_id
                        matched_name = player_locations.get(matched_id, {}).get("username")
                        if matched_name:
                            session.username = matched_name

            await room.broadcast(
                {
                    "type": "locations",
                    "locations": player_locations,
                    "pinMap": pin_to_user,
                }
            )


@asynccontextmanager
async def lifespan(_app: FastAPI) -> AsyncIterator[None]:
    task = asyncio.create_task(broadcast_locations_loop())
    logger.info("Continuous 3D location broadcast loop started (0.5s).")
    try:
        yield
    finally:
        task.cancel()


# ------------------------------------------------------------------------------
# FastAPI App
# ------------------------------------------------------------------------------
app = FastAPI(
    title="Roblox WebRTC 3D Spatial Voice (PIN Auth)",
    version="2.1.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ------------------------------------------------------------------------------
# HTTP Endpoints
# ------------------------------------------------------------------------------
@app.post("/update_locations")
async def update_locations(
    locations: dict[str, PlayerPosition],
    x_server_secret: str | None = Header(default=None),
) -> JSONResponse:
    """
    Receives player positions + PINs from Roblox HttpService:
    {
      "12345678": { "pin": "4829", "username": "Officer_Alex", "x": 10.5, "y": 5.0, "z": -20.0, "yaw": 0.5 }
    }
    """
    if ROBLOX_API_SECRET and x_server_secret != ROBLOX_API_SECRET:
        raise HTTPException(status_code=401, detail="Invalid X-Server-Secret header.")

    new_locations = {}
    new_pins = {}

    for uid, pos in locations.items():
        uid_str = str(uid)
        pin_str = str(pos.pin).strip()
        record = {
            "userId": uid_str,
            "pin": pin_str,
            "username": pos.username or f"Player_{uid_str[:4]}",
            "x": pos.x,
            "y": pos.y,
            "z": pos.z,
            "yaw": pos.yaw,
        }
        new_locations[uid_str] = record
        if pin_str:
            new_pins[pin_str] = uid_str

    player_locations.clear()
    player_locations.update(new_locations)

    pin_to_user.clear()
    pin_to_user.update(new_pins)

    active_connected_pins = [session.pin for session in room.peers.values() if session.pin]
    return JSONResponse(
        {
            "status": "ok",
            "trackedPlayers": len(player_locations),
            "activePins": len(pin_to_user),
            "activeVoicePins": active_connected_pins,
        }
    )


@app.get("/health")
async def health_check() -> JSONResponse:
    return JSONResponse(
        {
            "status": "ok",
            "onlinePeers": len(room.peers),
            "trackedPlayers": len(player_locations),
            "activePins": len(pin_to_user),
        }
    )


@app.get("/")
async def serve_index() -> FileResponse:
    return FileResponse(STATIC_DIR / "index.html")


app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")


# ------------------------------------------------------------------------------
# WebSocket Signaling Endpoint
# ------------------------------------------------------------------------------
@app.websocket("/ws")
async def signaling_websocket(
    websocket: WebSocket,
    pin: str = Query(default=""),
    username: str = Query(default=""),
) -> None:
    session = await room.connect(websocket, raw_pin=pin, raw_username=username)

    try:
        while True:
            data = await websocket.receive_json()
            msg_type = data.get("type")

            if msg_type == "ping":
                await room._safe_send(session, {"type": "pong"})
                continue

            if msg_type in ("offer", "answer", "ice-candidate"):
                target_id = data.get("target")
                if isinstance(target_id, str) and target_id:
                    await room.relay_to_peer(session, target_id, data)
                continue

    except WebSocketDisconnect:
        pass
    finally:
        await room.disconnect(session.peer_id)


